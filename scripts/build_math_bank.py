def strip_makers(node):
    if isinstance(node, dict):
        return {k: strip_makers(v) for k, v in node.items() if k != "_maker"}
    if isinstance(node, list):
        return [strip_makers(v) for v in node]
    return node


def main():
    existing = json.loads(EXISTING.read_text(encoding="utf-8"))
    bank = Bank()
    for q in existing["questions"]:
        bank.ids.add(q["id"])
        bank.questions.append(q)
    books = build_books(existing["chapter"])
    for b in books:
        for ch in b["chapters"]:
            for un in ch["units"]:
                meta = {"grade": b["grade"], "semester": b["semester"], "chapterId": ch["id"], "unitId": un["id"]}
                for kp in un["knowledgePoints"]:
                    maker = kp.get("_maker")
                    if not maker:
                        continue
                    pack(bank, meta, kp, MAKERS[maker](meta, kp))
    unit_ids = [un["id"] for b in books for ch in b["chapters"] for un in ch["units"]]
    if len(unit_ids) != len(set(unit_ids)):
        raise SystemExit("duplicate unit id")
    covered = {q["unitId"] for q in bank.questions}
    missing = [u for u in unit_ids if u not in covered]
    if missing:
        raise SystemExit(f"missing {missing}")
    by_grade = {}
    exam_n = 0
    for q in bank.questions:
        by_grade[q["grade"]] = by_grade.get(q["grade"], 0) + 1
        if q.get("source", {}).get("exam") == "自編會考練習":
            exam_n += 1
            if "會考練習" not in q["tags"]:
                raise SystemExit("tag")
        if q["type"] == "single" and q["answer"] not in "ABCD":
            raise SystemExit(q["id"])
    OUT.write_text(json.dumps({"books": strip_makers(books), "questions": bank.questions}, ensure_ascii=False, indent=2), encoding="utf-8")
    print(f"questions={len(bank.questions)} units={len(unit_ids)} exam={exam_n} by_grade={by_grade}")


if __name__ == "__main__":
    main()
