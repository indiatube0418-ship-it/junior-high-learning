MINUS = "−"


def fmt_int(n: int) -> str:
    if n < 0:
        return f"{MINUS}{abs(n)}"
    return str(n)


def fmt_frac(fr: Fraction) -> str:
    fr = Fraction(fr)
    if fr.denominator == 1:
        return fmt_int(fr.numerator)
    sign = MINUS if fr < 0 else ""
    return f"{sign}{abs(fr.numerator)}/{fr.denominator}"


class Bank:
    def __init__(self) -> None:
        self.questions: list[dict] = []
        self.ids: set[str] = set()

    def add(self, *, qid: str, meta: dict, kp_id: str, tier: str, qtype: str,
            stem: str, answer: str, explanation: str, tags: list[str],
            difficulty: int, wrongs: list[str] | None = None,
            exam: bool = False) -> None:
        if qid in self.ids:
            raise SystemExit(f"duplicate id {qid}")
        self.ids.add(qid)
        item = {
            "id": qid,
            "subject": "math",
            "grade": meta["grade"],
            "semester": meta["semester"],
            "chapterId": meta["chapterId"],
            "unitId": meta["unitId"],
            "knowledgePointId": kp_id,
            "tier": tier,
            "type": qtype,
            "stem": stem,
            "answer": answer,
            "explanation": explanation,
            "tags": tags + (["會考練習"] if exam else []),
            "difficulty": difficulty,
        }
        if exam:
            item["source"] = {"year": 0, "exam": "自編會考練習", "number": len(self.questions) + 1}
        if qtype == "single":
            if not wrongs or len(wrongs) < 3:
                raise SystemExit(f"{qid} needs 3 wrong options")
            wrongs = wrongs[:3]
            if answer in wrongs or len({answer, *wrongs}) < 4:
                raise SystemExit(f"{qid} options not unique: {answer} {wrongs}")
            options = [wrongs[0], answer, wrongs[1], wrongs[2]]
            item["options"] = options
            item["answer"] = "B"
            item["explanation"] = f"{explanation} 答案是 {answer}。"
        self.questions.append(item)


def qid_for(meta: dict, kp_id: str, n: int) -> str:
    return f"math-{meta['grade']}-{meta['semester']}-{meta['chapterId']}-{meta['unitId']}-{kp_id}-{n}"


def pack(bank: Bank, meta: dict, kp: dict, built: list[dict]) -> None:
    if len(built) != 4:
        raise SystemExit(f"{kp['id']} expected 4 questions, got {len(built)}")
    tiers = [("basic", 1, False), ("basic", 2, False), ("advanced", 3, False), ("exam", 4, True)]
    for n, (spec, (tier, diff, exam)) in enumerate(zip(built, tiers), start=1):
        bank.add(
            qid=qid_for(meta, kp["id"], n),
            meta=meta,
            kp_id=kp["id"],
            tier=tier,
            qtype=spec["type"],
            stem=spec["stem"],
            answer=spec["answer"],
            explanation=spec["explanation"],
            tags=spec["tags"],
            difficulty=diff,
            wrongs=spec.get("wrongs"),
            exam=exam,
        )


