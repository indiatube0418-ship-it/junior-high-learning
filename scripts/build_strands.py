def main():
    src = json.load(open(SRC, encoding="utf-8"))
    old_units = {}
    for book in src["books"]:
        for ch in book["chapters"]:
            for u in ch["units"]:
                old_units[u["id"]] = u
    q_by_unit = {}
    for q in src["questions"]:
        q_by_unit.setdefault(q["unitId"], []).append(q)

    missing = [uid for uid in ASSIGN if uid not in old_units]
    if missing:
        raise SystemExit("missing units " + ",".join(missing))
    extra = set(old_units) - set(ASSIGN)
    if extra:
        raise SystemExit("unassigned " + ",".join(extra))

    banks = {k: {"books": [], "questions": []} for k in ("history", "geography", "civics")}
    used = set()
    figures = {}

    def emit_new_question(subject, grade, sem, chapter_id, u, seq, spec):
        kp = u["id"] + "-kp1"
        return {
            "id": f"{subject}-{grade}-{sem}-{chapter_id}-{u['id']}-{kp}-{seq}",
            "subject": subject,
            "grade": grade,
            "semester": sem,
            "chapterId": chapter_id,
            "unitId": u["id"],
            "knowledgePointId": kp,
            "tier": spec["tier"],
            "type": "single",
            "stem": spec["stem"],
            "options": spec["options"],
            "answer": spec["answer"],
            "explanation": spec["explanation"],
            "tags": [u["title"]],
            "difficulty": spec["difficulty"],
        }

    for subject, books in LAYOUT.items():
        for bid, title, grade, sem, chapters in books:
            book = {"id": bid, "title": title, "grade": grade, "semester": sem, "subject": subject, "chapters": []}
            for cid, ctitle, uids in chapters:
                units = []
                for uid in uids:
                    used.add(uid)
                    if uid in old_units:
                        units.append(old_units[uid])
                        for q in q_by_unit[uid]:
                            nq = dict(q)
                            nq["subject"] = subject
                            nq["chapterId"] = cid
                            nq["grade"] = grade
                            nq["semester"] = sem
                            banks[subject]["questions"].append(nq)
                    else:
                        spec = NEW[uid]
                        kp = uid + "-kp1"
                        units.append({
                            "id": uid,
                            "title": spec["title"],
                            "knowledgePoints": [{"id": kp, "title": spec["title"], "lesson": spec["lesson"]}],
                        })
                        figures[kp] = {"title": spec["title"], "captions": spec["lesson"], "boxes": spec["boxes"]}
                        for i, qq in enumerate(spec["questions"], 1):
                            banks[subject]["questions"].append(emit_new_question(subject, grade, sem, cid, spec, i, qq))
                book["chapters"].append({"id": cid, "title": ctitle, "units": units})
            banks[subject]["books"].append(book)

    if used != set(ASSIGN) | set(NEW):
        raise SystemExit("layout mismatch " + str(sorted(set(ASSIGN) | set(NEW) ^ used))[:500])

    sci_bank = {"books": [], "questions": []}
    for bid, title, grade, sem, chapters in sci_layout():
        book = {"id": bid, "title": title, "grade": grade, "semester": sem, "subject": "science", "chapters": []}
        for cid, ctitle, uids in chapters:
            units = []
            for uid in uids:
                spec = sci_units[uid]
                kp = uid + "-kp1"
                units.append({
                    "id": uid,
                    "title": spec["title"],
                    "knowledgePoints": [{"id": kp, "title": spec["title"], "lesson": spec["lesson"]}],
                })
                figures[kp] = {"title": spec["title"], "captions": spec["lesson"], "boxes": spec["boxes"]}
                for i, qq in enumerate(spec["questions"], 1):
                    sci_bank["questions"].append(emit_new_question("science", grade, sem, cid, spec, i, qq))
            book["chapters"].append({"id": cid, "title": ctitle, "units": units})
        sci_bank["books"].append(book)

    def check(bank, subject):
        ids = []
        units = 0
        for b in bank["books"]:
            assert b["subject"] == subject
            for ch in b["chapters"]:
                for u in ch["units"]:
                    units += 1
                    kp = u["knowledgePoints"][0]["id"]
                    qs = [q for q in bank["questions"] if q["unitId"] == u["id"]]
                    assert len(qs) == 4, (u["id"], len(qs))
                    tiers = [q["tier"] for q in qs]
                    assert tiers.count("basic") == 2 and "advanced" in tiers and "exam" in tiers
                    for q in qs:
                        assert q["answer"] in ("A", "B", "C", "D")
                        assert len(q["options"]) == 4
                        assert len(u["knowledgePoints"][0]["lesson"]) == 4
                        ids.append(q["id"])
                    if kp in figures:
                        assert len(figures[kp]["captions"]) == 4
                        assert len(figures[kp]["boxes"]) == 4
        assert len(ids) == len(set(ids))
        return units, len(ids)

    summary = []
    paths = {
        "history": "history-bank.json",
        "geography": "geography-bank.json",
        "civics": "civics-bank.json",
    }
    for subject, name in paths.items():
        units, nq = check(banks[subject], subject)
        path = os.path.join(ROOT, "data", name)
        json.dump(banks[subject], open(path, "w", encoding="utf-8"), ensure_ascii=False, indent=2)
        summary.append(f"{subject} units={units} questions={nq}")
    units, nq = check(sci_bank, "science")
    json.dump(sci_bank, open(os.path.join(ROOT, "data", "science-bank.json"), "w", encoding="utf-8"), ensure_ascii=False, indent=2)
    summary.append(f"science units={units} questions={nq}")

    # figures ts
    lines = [
        "import type { Visual } from './draw';",
        "",
        "interface ConceptFigure {",
        "  title: string;",
        "  captions: [string, string, string, string];",
        "  visual: Visual;",
        "  voice: 'concept';",
        "}",
        "",
        "function fig(",
        "  title: string,",
        "  captions: [string, string, string, string],",
        "  phases: { boxes: string[]; hot?: number; result?: string }[],",
        "): ConceptFigure {",
        "  return { title, captions, voice: 'concept', visual: { type: 'flow', phases } };",
        "}",
        "",
        "export const strandFigures: Record<string, ConceptFigure> = {",
    ]
    for kp, fig in figures.items():
        caps = json.dumps(fig["captions"], ensure_ascii=False)
        phases = []
        for i, boxes in enumerate(fig["boxes"]):
            phase = {"boxes": boxes}
            if i > 0:
                phase["hot"] = 0
            if i == 3:
                phase["result"] = boxes[-1]
            phases.append(phase)
        lines.append(f"  {json.dumps(kp, ensure_ascii=False)}: fig({json.dumps(fig['title'], ensure_ascii=False)}, {caps} as [string, string, string, string], {json.dumps(phases, ensure_ascii=False)}),")
    lines.append("};")
    lines.append("")
    fig_path = os.path.join(ROOT, "components", "figures", "strandCatalog.ts")
    open(fig_path, "w", encoding="utf-8", newline="\n").write("\n".join(lines))
    summary.append(f"figures={len(figures)}")
    print("\n".join(summary))


if __name__ == "__main__":
    main()
